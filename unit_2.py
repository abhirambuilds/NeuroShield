"""## 18. Train Bayesian Logistic Regression

Bayesian Logistic Regression extends logistic regression by treating model parameters probabilistically rather than estimating only a single fixed set of coefficients.

This approach is particularly relevant to NeuroShield because the project investigates whether probabilistic predictions can provide information about uncertainty.

For the prototype, we use a Bayesian logistic regression implementation that provides probability estimates for the predicted classes.
"""

# Install the Bayesian modeling library if necessary (run via pip in terminal)
# !pip -q install pymc

import pymc as pm
import arviz as az

print("PyMC version:", pm.__version__)

"""## 19. Prepare Data for Bayesian Logistic Regression

Bayesian modeling requires a numerical representation of the target classes.

We therefore encode the workload labels into numerical class values while preserving a mapping back to their original labels.

The feature preprocessing pipeline is fitted using only the training data to prevent information leakage from the test set.

We will use the processed training and testing matrices as inputs to the Bayesian model.
"""

from sklearn.preprocessing import LabelEncoder

# Encode target labels
label_encoder = LabelEncoder()

y_train_encoded = label_encoder.fit_transform(y_train)
y_test_encoded = label_encoder.transform(y_test)

# Fit preprocessing only on training data
X_train_processed = preprocessor.fit_transform(X_train)
X_test_processed = preprocessor.transform(X_test)

print("Classes:", list(label_encoder.classes_))
print("Training matrix shape:", X_train_processed.shape)
print("Testing matrix shape:", X_test_processed.shape)

"""## 20. Build the Bayesian Logistic Regression Model

In this section, we construct the Bayesian Logistic Regression model using PyMC.

The model places probability distributions, called priors, over the regression coefficients. The observed training data is then used to estimate the posterior distribution of these coefficients.

For binary cognitive workload classification, the model uses a logistic probability function to estimate the probability that an observation belongs to the high-workload class.

The resulting posterior distribution allows us to obtain probability-based predictions rather than only a hard class label.
"""

# Bayesian Logistic Regression
# This implementation assumes binary classification.

if len(label_encoder.classes_) != 2:
    raise ValueError(
        f"Bayesian Logistic Regression cell currently expects "
        f"2 classes, but found {len(label_encoder.classes_)}: "
        f"{list(label_encoder.classes_)}"
    )

n_features = X_train_processed.shape[1]

with pm.Model() as bayesian_logistic_model:

    # Priors
    beta = pm.Normal(
        "beta",
        mu=0,
        sigma=1,
        shape=n_features
    )

    intercept = pm.Normal(
        "intercept",
        mu=0,
        sigma=1
    )

    # Logistic probability
    logits = intercept + pm.math.dot(
        X_train_processed,
        beta
    )

    probability = pm.math.sigmoid(logits)

    # Likelihood
    observed = pm.Bernoulli(
        "observed",
        p=probability,
        observed=y_train_encoded
    )

    # Sample posterior
    trace = pm.sample(
        draws=500,
        tune=500,
        chains=2,
        cores=2,
        random_seed=42,
        target_accept=0.9,
        progressbar=True
    )

print("Bayesian model training completed.")

"""## 21. Generate Bayesian Probability Predictions

The Bayesian Logistic Regression model does not produce only a single class prediction.

Instead, the posterior distribution of the model parameters allows us to estimate the probability of each workload class.

In this section, we use the posterior samples to generate predictions for the unseen test data.

These probabilities will later be used to investigate the uncertainty-aware aspect of NeuroShield.
"""

# Generate posterior predictions for the test set

with bayesian_logistic_model:
    posterior_predictions = pm.sample_posterior_predictive(
        trace,
        var_names=["observed"],
        random_seed=42,
        progressbar=True
    )

# Extract predictions from posterior samples
posterior_samples = (
    posterior_predictions.posterior_predictive["observed"]
    .stack(sample=("chain", "draw"))
    .values
)

# Average probability of class 1 across posterior samples
bayesian_probability = posterior_samples.mean(axis=1)

# Convert probability into a class prediction
bayesian_predictions = (
    bayesian_probability >= 0.5
).astype(int)

print("Bayesian predictions generated.")
print("Number of test predictions:", len(bayesian_predictions))

print("\nFirst 10 predicted probabilities:")
print(bayesian_probability[:10])

print("\nFirst 10 predicted classes:")
print(bayesian_predictions[:10])

"""## 22. Inspect Bayesian Posterior Output

The Bayesian model was trained using the training observations, while our evaluation requires predictions for the unseen test observations.

Before generating the final Bayesian predictions, we inspect the dimensions of the posterior samples produced by PyMC. This allows us to correctly understand the structure of the Bayesian model output and avoid comparing predictions from the training data with test labels.

No evaluation metrics are calculated in this step.
"""

# Inspect the Bayesian model and posterior output

print("Training observations:", X_train_processed.shape[0])
print("Testing observations:", X_test_processed.shape[0])

print("\nPosterior predictive variables:")
print(posterior_predictions.posterior_predictive)

print("\nObserved prediction dimensions:")
print(
    posterior_predictions
    .posterior_predictive["observed"]
    .dims
)

print("\nObserved prediction shape:")
print(
    posterior_predictions
    .posterior_predictive["observed"]
    .shape
)

"""## 23. Generate Bayesian Predictions for the Test Set

The Bayesian model was trained using the training dataset. Its posterior distribution contains many possible values for the model coefficients.

In this section, we use those posterior coefficient samples to calculate predictions for the unseen test dataset.

For every test observation, we calculate the logistic probability across the posterior samples and average these probabilities to obtain an uncertainty-aware prediction.

Unlike the previous approach, this explicitly uses `X_test_processed`, so the number of predictions will match the number of test observations.
"""

# Extract posterior samples for model parameters

beta_samples = (
    trace.posterior["beta"]
    .stack(sample=("chain", "draw"))
    .values
)

intercept_samples = (
    trace.posterior["intercept"]
    .stack(sample=("chain", "draw"))
    .values
)

print("Beta samples shape:", beta_samples.shape)
print("Intercept samples shape:", intercept_samples.shape)

# Make sure beta has shape:
# (number_of_features, number_of_posterior_samples)

if beta_samples.shape[0] != X_test_processed.shape[1]:
    beta_samples = beta_samples.T

# Calculate logits for every posterior sample and test observation
#
# Result:
# (posterior_samples, test_observations)

logits = (
    X_test_processed @ beta_samples
    + intercept_samples
)

# Logistic/sigmoid function
test_probabilities = 1 / (1 + np.exp(-logits))

print("\nProbability matrix shape:", test_probabilities.shape)

# Average probability across posterior samples
bayesian_probability = test_probabilities.mean(axis=1)

print(
    "Number of test probabilities:",
    len(bayesian_probability)
)

print(
    "Number of test observations:",
    len(y_test_encoded)
)

# Sanity check
assert len(bayesian_probability) == len(y_test_encoded)

# Convert probability into predicted class
bayesian_predictions = (
    bayesian_probability >= 0.5
).astype(int)

print("\nBayesian test predictions generated successfully!")

print("\nFirst 10 probabilities:")
print(bayesian_probability[:10])

print("\nFirst 10 predictions:")
print(bayesian_predictions[:10])

